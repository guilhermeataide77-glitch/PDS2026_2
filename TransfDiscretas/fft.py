def medir_tempo(funcao, x, repeticoes=3):
    tempos = []

    for _ in range(repeticoes):
        inicio = time.perf_counter()
        funcao(x)
        fim = time.perf_counter()

        tempos.append(fim - inicio)

    return float(np.median(tempos))


