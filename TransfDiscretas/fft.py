def fft_radix2(x):
    x = np.asarray(x, dtype=complex)
    N = len(x)

    if N == 0 or (N & (N - 1)) != 0:
        raise ValueError(
            "O comprimento precisa ser uma potência de 2."
        )

    bits = N.bit_length() - 1
    indices = np.zeros(N, dtype=int)

    for i in range(N):
        valor = i
        reverso = 0

        for _ in range(bits):
            reverso = (reverso << 1) | (valor & 1)
            valor >>= 1

        indices[i] = reverso

    a = x[indices].copy()

    tamanho = 2

    while tamanho <= N:
        metade = tamanho // 2

        fatores = np.exp(
            -2j * np.pi * np.arange(metade) / tamanho
        )

        for inicio in range(0, N, tamanho):
            par = a[inicio:inicio + metade].copy()

            impar = (
                a[inicio + metade:inicio + tamanho].copy()
                * fatores
            )

            a[inicio:inicio + metade] = par + impar
            a[inicio + metade:inicio + tamanho] = par - impar

        tamanho *= 2

    return a


def ifft_radix2(X):
    X = np.asarray(X, dtype=complex)

    return np.conj(fft_radix2(np.conj(X))) / len(X)


