plt.xlabel("n")
plt.grid(True)

plt.subplot(1, 2, 2)
plt.stem(np.arange(N), np.abs(X), basefmt="k-")
plt.title("Espectro de Magnitude |X[k]|")
plt.xlabel("k")
plt.grid(True)

plt.tight_layout()
plt.show()